def load_notified_urls(path: Path) -> set[str]:
    """Load previously notified project URLs.

    Example:
        urls = load_notified_urls(Path("data/notified.json"))
    """
    if not path.exists():
        return set()
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise ValueError(f"Invalid notified file {path}; expected JSON string list.")
    return {item for item in data if isinstance(item, str)}


def save_notified_urls(path: Path, urls: set[str]) -> None:
    """Save notified project URLs as a sorted JSON list.

    Example:
        save_notified_urls(Path("data/notified.json"), {"url"})
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(sorted(urls), indent=2) + "\n", encoding="utf-8")


def object_json(value: object, label: str) -> dict[str, object]:
    """Validate that a JSON value is an object.

    Example:
        payload = object_json({}, "payload")
    """
    if isinstance(value, dict):
        return value
    raise ValueError(f"Invalid {label}; expected object, got {type(value).__name__}.")


def required_score(payload: dict[str, object], key: str) -> int:
    """Return a required 0-100 integer score.

    Example:
        score = required_score({"score": 75}, "score")
    """
    value = payload.get(key)
    if isinstance(value, int) and 0 <= value <= 100:
        return value
    raise ValueError(f"Invalid AI field {key}={value!r}; expected integer 0-100.")


def required_recommendation(payload: dict[str, object]) -> str:
    """Return a validated recommendation value.

    Example:
        recommendation = required_recommendation({"recommendation": "apply"})
    """
    value = payload.get("recommendation")
    if value in {"apply", "maybe", "skip"}:
        return str(value)
    raise ValueError(
        f"Invalid recommendation {value!r}; expected apply, maybe, or skip."
    )


def optional_string(payload: dict[str, object], key: str) -> str:
    """Return an optional string field or an empty string.

    Example:
        text = optional_string({}, "summary")
    """
    value = payload.get(key)
    return value if isinstance(value, str) else ""


def string_tuple(payload: dict[str, object], key: str) -> tuple[str, ...]:
    """Return a tuple of strings from an optional JSON list.

    Example:
        values = string_tuple({"items": ["a"]}, "items")
    """
    value = payload.get(key)
    if not isinstance(value, list):
        return ()
    return tuple(item for item in value if isinstance(item, str))


def required_project_string(project: dict[str, object], key: str) -> str:
    """Return a required project string field.

    Example:
        title = required_project_string({"title": "A"}, "title")
    """
    value = project.get(key)
    if isinstance(value, str) and value:
        return value
    raise ValueError(
        f"Invalid project field {key}={value!r}; expected non-empty string."
    )
