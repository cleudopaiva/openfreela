class ProjectJudge(Protocol):
    """Protocol for AI clients that evaluate rendered prompts.

    Example:
        content = judge.chat_json(prompt)
    """

    def chat_json(self, prompt: str) -> str:
        """Return JSON text generated by the AI model."""


class ProjectNotifier(Protocol):
    """Protocol for notification clients.

    Example:
        notifier.send_message("Project matched")
    """

    def send_message(self, text: str) -> None:
        """Send one notification message."""


@dataclass(frozen=True)
class ProjectEvaluation:
    """AI evaluation for one freelance project.

    Example:
        evaluation = ProjectEvaluation(
            "url", "Title", 80, 70, "apply", "", "", (), (), (), (), ""
        )
    """

    project_url: str
    title: str
    profile_match_score: int
    execution_confidence_score: int
    recommendation: str
    summary: str
    why_apply: str
    cv_matches: tuple[str, ...]
    adjacent_skills: tuple[str, ...]
    missing_skills: tuple[str, ...]
    risks: tuple[str, ...]
    proposal_angle: str

    def to_dict(self) -> dict[str, object]:
        """Return a JSON-serializable evaluation dictionary.

        Example:
            payload = evaluation.to_dict()
        """
        return {
            "project_url": self.project_url,
            "title": self.title,
            "profile_match_score": self.profile_match_score,
            "execution_confidence_score": self.execution_confidence_score,
            "recommendation": self.recommendation,
            "summary": self.summary,
            "why_apply": self.why_apply,
            "cv_matches": list(self.cv_matches),
            "adjacent_skills": list(self.adjacent_skills),
            "missing_skills": list(self.missing_skills),
            "risks": list(self.risks),
            "proposal_angle": self.proposal_angle,
        }


@dataclass(frozen=True)
class EvaluationRunConfig:
    """File paths and filters for a project evaluation run.

    Example:
        config = EvaluationRunConfig(
            Path("projects.json"), Path("cv.md"), Path("prompt.md"),
            Path("out.json"), Path("notified.json"), 30
        )
    """

    projects_path: Path
    cv_path: Path
    prompt_path: Path
    output_path: Path
    notified_path: Path
    max_proposals: int | None = None


def evaluate_project_file(
    config: EvaluationRunConfig,
    judge: ProjectJudge,
    notifier: ProjectNotifier,
) -> list[ProjectEvaluation]:
    """Evaluate scraped projects, save results, and notify strong matches.

    Example:
        evaluations = evaluate_project_file(config, judge, notifier)
    """
    from openfreela.evaluation.runner import run_project_evaluation_file

    return run_project_evaluation_file(config, judge, notifier)


def render_prompt(template: str, cv: str, project: dict[str, object]) -> str:
    """Render the editable Markdown prompt with CV and project JSON.

    Example:
        prompt = render_prompt("{{cv}} {{project}}", "CV", {"title": "A"})
    """
    project_json = json.dumps(project, ensure_ascii=False, indent=2)
    return template.replace("{{cv}}", cv).replace("{{project}}", project_json)


def parse_project_evaluation(
    content: str, project: dict[str, object]
) -> ProjectEvaluation:
    """Parse and validate one AI JSON response.

    Example:
        evaluation = parse_project_evaluation('{"profile_match_score": 80}', project)
    """
    payload = object_json(load_json_object(content), "AI evaluation")
    recommendation = required_recommendation(payload)
    return ProjectEvaluation(
        project_url=required_project_string(project, "project_url"),
        title=required_project_string(project, "title"),
        profile_match_score=required_score(payload, "profile_match_score"),
        execution_confidence_score=required_score(
            payload, "execution_confidence_score"
        ),
        recommendation=recommendation,
        summary=optional_string(payload, "summary"),
        why_apply=optional_string(payload, "why_apply"),
        cv_matches=string_tuple(payload, "cv_matches"),
        adjacent_skills=string_tuple(payload, "adjacent_skills"),
        missing_skills=string_tuple(payload, "missing_skills"),
        risks=string_tuple(payload, "risks"),
        proposal_angle=optional_string(payload, "proposal_angle"),
    )


def load_json_object(content: str) -> object:
    """Load AI JSON, allowing surrounding markdown or prose.

    Example:
        payload = load_json_object('```json\n{"a": 1}\n```')
    """
    try:
        return json.loads(content)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", content, flags=re.DOTALL)
        if match is None:
            raise
        return json.loads(match.group(0))


def should_notify(
    evaluation: ProjectEvaluation,
    notified_urls: set[str],
) -> bool:
    """Return whether an evaluation should trigger a notification.

    Example:
        ok = should_notify(evaluation, set())
    """
    return (
        evaluation.recommendation == "apply"
        and evaluation.project_url not in notified_urls
    )


def notification_message(evaluation: ProjectEvaluation) -> str:
    """Format one Telegram notification message.

    Example:
        text = notification_message(evaluation)
    """
    return "\n".join(
        [
            f"OpenFreela match: {evaluation.profile_match_score}%",
            f"Execution confidence: {evaluation.execution_confidence_score}%",
            f"Recommendation: {evaluation.recommendation}",
            "",
            f"Project: {evaluation.title}",
            "",
            f"Why apply: {evaluation.why_apply or evaluation.summary}",
            "",
            f"URL: {evaluation.project_url}",
        ]
    )


def read_required_text(path: Path) -> str:
    """Read a required UTF-8 text file.

    Example:
        text = read_required_text(Path("profile/cv.md"))
    """
    if not path.exists():
        message = f"Missing required file {path}; expected a readable Markdown file."
        raise FileNotFoundError(message)
    return path.read_text(encoding="utf-8")


def load_project_objects(path: Path) -> list[dict[str, object]]:
    """Load scraped project objects from JSON.

    Example:
        projects = load_project_objects(Path("data/projects.json"))
    """
    data = json.loads(read_required_text(path))
    if not isinstance(data, list):
        raise ValueError(f"Invalid projects file {path}; expected JSON list.")
    return [
        object_json(item, f"project at index {index}")
        for index, item in enumerate(data)
    ]


def save_evaluations(path: Path, evaluations: list[ProjectEvaluation]) -> None:
    """Save project evaluations as pretty JSON.

    Example:
        save_evaluations(Path("data/evals.json"), evaluations)
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = [evaluation.to_dict() for evaluation in evaluations]
    path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def load_evaluations(path: Path) -> list[ProjectEvaluation]:
    """Load existing successful evaluations from JSON if present.

    Example:
        evaluations = load_evaluations(Path("data/evals.json"))
    """
    if not path.exists():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise ValueError(f"Invalid evaluations file {path}; expected JSON list.")
    return [
        parse_saved_evaluation(object_json(item, f"evaluation at index {index}"))
        for index, item in enumerate(data)
    ]


